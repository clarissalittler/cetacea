#!/usr/bin/env python3
"""Generate `web2/book.js` from the book's companion files.

The browser's Book menu is built from this module, so a student opens
exactly the files the chapters talk about, without copying anything.

    python3 scripts/build_web_book.py            # rewrite web2/book.js
    python3 scripts/build_web_book.py --check    # fail if it is stale (CI)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOOK = ROOT / "docs" / "book"
OUTPUT = ROOT / "web2" / "book.js"

# The order the chapters use, and what the menu calls each kind of file.
KINDS = [
    ("examples", "Examples"),
    ("mistakes", "Mistakes (meant to fail)"),
    ("fallacies", "Fallacies (meant to fail)"),
    ("exercises", "Exercises"),
    ("solutions", "Solutions"),
]


def chapters() -> list[dict]:
    out = []
    for chapter in sorted(BOOK.glob("[0-9][0-9]-*.md")):
        number = chapter.name[:2]
        heading = chapter.read_text(encoding="utf-8").splitlines()[0]
        match = re.match(r"#\s*Chapter\s+\d+\s*[—-]\s*(.+)", heading)
        if not match:
            raise SystemExit(f"error: {chapter.name} does not start with a chapter heading")
        files = []
        for kind, label in KINDS:
            path = BOOK / "code" / f"ch{number}-{kind}.ctea"
            if path.exists():
                files.append(
                    {
                        "kind": kind,
                        "label": label,
                        "name": path.name,
                        "source": path.read_text(encoding="utf-8"),
                    }
                )
        out.append(
            {
                "number": int(number),
                # The course section that goes with the chapter.
                "section": f"ch{number}",
                "title": match.group(1).strip(),
                "files": files,
            }
        )
    return out


def render() -> str:
    return (
        "// The book's companion files, offered by the Book menu.\n"
        "// GENERATED by scripts/build_web_book.py from docs/book/code; do not edit by hand.\n\n"
        f"export const BOOK = {json.dumps(chapters(), indent=1, ensure_ascii=False)};\n"
    )


def main(argv: list[str]) -> int:
    rendered = render()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(
                f"error: {OUTPUT.relative_to(ROOT)} is out of date; run "
                "`python3 scripts/build_web_book.py`",
                file=sys.stderr,
            )
            return 1
        print(f"verified {OUTPUT.relative_to(ROOT)}")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
