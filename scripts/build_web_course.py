#!/usr/bin/env python3
"""Generate `web2/course.js` from a course definition.

The browser's Section menu is built from this module, so the rules a
student sees in the browser are the rules the command line grades with.

    python3 scripts/build_web_course.py            # rewrite web2/course.js
    python3 scripts/build_web_course.py --check    # fail if it is stale (CI)
    python3 scripts/build_web_course.py courses/my-course.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_COURSE = ROOT / "courses" / "proofs-checked.json"
OUTPUT = ROOT / "web2" / "course.js"


def render(course_path: Path) -> str:
    course = json.loads(course_path.read_text(encoding="utf-8"))
    try:
        shown = course_path.resolve().relative_to(ROOT)
    except ValueError:
        shown = course_path
    return (
        "// The course whose sections the Section menu offers.\n"
        f"// GENERATED by scripts/build_web_course.py from {shown}; do not edit by hand.\n\n"
        f"export const COURSE = {json.dumps(course, indent=2, ensure_ascii=False)};\n"
    )


def main(argv: list[str]) -> int:
    paths = [Path(a) for a in argv if not a.startswith("--")]
    course_path = paths[0] if paths else DEFAULT_COURSE
    rendered = render(course_path)
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(
                f"error: {OUTPUT.relative_to(ROOT)} is out of date; run "
                "`python3 scripts/build_web_course.py`",
                file=sys.stderr,
            )
            return 1
        print(f"verified {OUTPUT.relative_to(ROOT)}")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
