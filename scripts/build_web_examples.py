#!/usr/bin/env python3
"""Generate `web/examples.js` from the repository's example sources.

The browser UI bundles a handful of `.ctea` files as `window.CETACEA_EXAMPLES`.
Those copies used to be pasted by hand and drifted from the files that
`scripts/check_all.sh` actually checks. This script is the single source of
truth for the bundle:

    python3 scripts/build_web_examples.py          # rewrite web/examples.js
    python3 scripts/build_web_examples.py --check  # fail if it is stale (CI)

Import lines are rewritten from on-disk relative paths such as
`import ../../../std/prelude.ctea` to the virtual `std/...` paths the wasm
module registers, so the examples check in the browser exactly as they do
natively.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "web" / "examples.js"

# (id, label, path) in display order.
EXAMPLES = [
    ("pigeonhole-collision", "Pigeonhole: explicit and classical witnesses", "docs/hol/examples/pigeonhole_collision.ctea"),
    ("finite-enumeration", "Finite enumeration: three colours", "docs/hol/examples/finite_enumeration.ctea"),
    ("probability-counts", "Chapter 22: finite probability and tickets", "docs/book/hol-code/ch22-examples.ctea"),
    ("recurrences", "Chapter 21: recurrences and closed forms", "docs/book/hol-code/ch21-examples.ctea"),
    ("modular-arithmetic", "Chapter 20: divisibility and clocks", "docs/book/hol-code/ch20-examples.ctea"),
    ("double-counting", "Chapter 19: counting twice", "docs/book/hol-code/ch19-examples.ctea"),
    ("explicit-paths", "Chapter 18: explicit directed paths", "docs/book/hol-code/ch18-examples.ctea"),
    ("finite-sums", "Chapter 17: finite sums", "docs/book/hol-code/ch17-examples.ctea"),
    (
        "hol-cardinality",
        "HOL Cardinality: map and transport",
        "docs/hol/examples/cardinality_map_length.ctea",
    ),
    ("hol-finite", "HOL Finite: cardinality of One", "docs/hol/examples/finite_one.ctea"),
    ("hol-list", "HOL List: length of append", "docs/hol/examples/list_length_append.ctea"),
    ("prop", "Propositional logic", "examples/prop.ctea"),
    ("fol", "First-order logic", "examples/fol.ctea"),
    ("set_nat", "Sets and natural numbers", "examples/set_nat.ctea"),
    ("cs250_01", "CS250 - 01 Propositional logic", "docs/cs250/code/01_propositional.ctea"),
    ("cs250_03", "CS250 - 03 First-order logic", "docs/cs250/code/03_first_order.ctea"),
    ("cs250_04", "CS250 - 04 Induction on Nat", "docs/cs250/code/04_induction_nat.ctea"),
    ("cs250_05", "CS250 - 05 Sets", "docs/cs250/code/05_sets.ctea"),
    ("cs250_06", "CS250 - 06 Relations", "docs/cs250/code/06_relations.ctea"),
    ("cs250_07", "CS250 - 07 Structural induction", "docs/cs250/code/07_structural_induction.ctea"),
    ("cs250_08", "CS250 - 08 Functions", "docs/cs250/code/08_functions.ctea"),
]

IMPORT_LINE = re.compile(r"^(import\s+)((?:\.\./)+)(std/\S+)(.*)$")

HEADER = """// Bundled example sources for the Cetacea browser UI.
// GENERATED by scripts/build_web_examples.py from the repository files listed
// in each entry's `path`; do not edit by hand. CI fails if this file is stale.
// Import lines are rewritten from on-disk relative paths (e.g.
// `import ../../../std/prelude.ctea`) to the virtual `std/...` paths that
// the wasm module registers, so the examples check in the browser.

window.CETACEA_EXAMPLES = [
"""


def virtualize_imports(source: str) -> str:
    lines = []
    for line in source.splitlines():
        match = IMPORT_LINE.match(line)
        lines.append(f"{match.group(1)}{match.group(3)}{match.group(4)}" if match else line)
    return "\n".join(lines).rstrip("\n") + "\n"


def template_literal(text: str) -> str:
    return text.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def render() -> str:
    parts = [HEADER]
    for identifier, label, path in EXAMPLES:
        source = (ROOT / path).read_text(encoding="utf-8")
        parts.append(
            "  {\n"
            f'    id: "{identifier}",\n'
            f'    label: "{label}",\n'
            f'    path: "{path}",\n'
            f"    source: `{template_literal(virtualize_imports(source))}`,\n"
            "  },\n"
        )
    parts.append("];\n")
    return "".join(parts)


def main(argv: list[str]) -> int:
    rendered = render()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(
                f"error: {OUTPUT.relative_to(ROOT)} is out of date; run "
                "`python3 scripts/build_web_examples.py`",
                file=sys.stderr,
            )
            return 1
        print(f"verified {OUTPUT.relative_to(ROOT)}: {len(EXAMPLES)} bundled examples")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(EXAMPLES)} bundled examples")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
